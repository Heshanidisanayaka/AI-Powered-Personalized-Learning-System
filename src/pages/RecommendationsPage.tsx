import React, { useState } from 'react';
import {
  Sparkles,
  BrainCircuit,
  Clock,
  ArrowRight,
  PlusCircle,
  Check,
  TrendingUp,
  AlertCircle,
  HelpCircle,
  BookOpen,
  Filter,
  CheckCircle2
} from 'lucide-react';
import { useApp } from '../context/AppContext';
import { Recommendation } from '../types';

export const RecommendationsPage: React.FC = () => {
  const {
    recommendations,
    addStudyTask,
    setCurrentPage,
    addToast
  } = useApp();

  const [selectedType, setSelectedType] = useState<string>('All');
  const [addedTasks, setAddedTasks] = useState<Record<string, boolean>>({});

  const types = ['All', 'Interactive Lab', 'Concept Deep Dive', 'Practice Drill', 'Flashcard Deck'];

  const filteredRecs = recommendations.filter((rec) => {
    if (selectedType === 'All') return true;
    return rec.type === selectedType;
  });

  const handleAddToPlan = (rec: Recommendation) => {
    addStudyTask({
      title: rec.title,
      course: rec.category,
      dueDate: 'Tomorrow, 5:00 PM',
      durationMinutes: parseInt(rec.estimatedTime) || 20,
      completed: false,
      priority: rec.matchScore >= 95 ? 'High' : 'Medium',
      type: rec.type.includes('Drill') ? 'quiz' : 'reading',
      aiSuggested: true,
    });
    setAddedTasks((prev) => ({ ...prev, [rec.id]: true }));
  };

  return (
    <div className="space-y-6 pb-12">
      {/* Header Banner */}
      <div className="rounded-3xl border border-violet-200 bg-gradient-to-r from-violet-600 via-brand-600 to-indigo-700 p-6 sm:p-8 text-white shadow-lg shadow-violet-500/10">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-6">
          <div className="space-y-2 max-w-2xl">
            <div className="inline-flex items-center gap-1.5 rounded-full bg-white/15 px-3 py-1 text-xs font-semibold backdrop-blur-md">
              <BrainCircuit className="h-3.5 w-3.5 text-amber-300" />
              <span>Real-Time Diagnostic Engine Active</span>
            </div>
            <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight">
              Personalized Learning Recommendations
            </h1>
            <p className="text-xs sm:text-sm text-brand-100 leading-relaxed">
              Every resource here is generated by cross-referencing your recent quiz error logs, memory decay intervals, and mastery goals. Read the transparent <strong>"Why Recommended"</strong> diagnostic below each item.
            </p>
          </div>

          <div className="rounded-2xl bg-white/10 p-4 border border-white/20 backdrop-blur-md shrink-0 text-center">
            <span className="text-2xl font-black text-amber-300">98%</span>
            <p className="text-[11px] font-semibold text-white">Top Match Precision</p>
            <p className="text-[10px] text-brand-200 mt-0.5">Updated 10m ago</p>
          </div>
        </div>
      </div>

      {/* Filter Chips */}
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-slate-200 bg-white p-3 shadow-sm">
        <div className="flex items-center gap-2 text-xs font-bold text-slate-700">
          <Filter className="h-3.5 w-3.5 text-brand-600" />
          <span>Filter by Format:</span>
        </div>
        <div className="flex items-center gap-1.5 overflow-x-auto">
          {types.map((type) => (
            <button
              key={type}
              onClick={() => setSelectedType(type)}
              className={`rounded-xl px-3 py-1.5 text-xs font-semibold transition-all ${
                selectedType === type
                  ? 'bg-brand-600 text-white shadow-sm'
                  : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
              }`}
            >
              {type}
            </button>
          ))}
        </div>
      </div>

      {/* Recommendations Cards Grid */}
      <div className="space-y-5">
        {filteredRecs.map((rec) => {
          const isAdded = addedTasks[rec.id];

          return (
            <div
              key={rec.id}
              className="group rounded-3xl border border-slate-200/90 bg-white p-6 shadow-card hover:shadow-card-hover transition-all"
            >
              <div className="flex flex-col lg:flex-row lg:items-start justify-between gap-6">
                {/* Left Section: Details & Why Recommended Box */}
                <div className="flex-1 space-y-4">
                  {/* Top Badges */}
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="rounded-full bg-violet-100 px-3 py-1 text-xs font-bold text-violet-800 flex items-center gap-1">
                      <Sparkles className="h-3 w-3" /> {rec.matchScore}% AI Match
                    </span>
                    <span className="rounded-md bg-slate-100 px-2.5 py-1 text-xs font-semibold text-slate-600">
                      {rec.category}
                    </span>
                    <span className="rounded-md bg-brand-50 px-2.5 py-1 text-xs font-semibold text-brand-700">
                      {rec.type}
                    </span>
                    <span className="flex items-center gap-1 text-xs text-slate-500 font-medium">
                      <Clock className="h-3.5 w-3.5" /> {rec.estimatedTime}
                    </span>
                  </div>

                  {/* Title */}
                  <h3 className="text-lg font-bold text-slate-900 group-hover:text-brand-600 transition-colors">
                    {rec.title}
                  </h3>

                  {/* Highlight: WHY THIS IS RECOMMENDED (Core SaaS Value) */}
                  <div className="rounded-2xl border border-brand-100 bg-brand-50/50 p-4 space-y-1.5">
                    <div className="flex items-center gap-2 text-xs font-bold text-brand-900">
                      <BrainCircuit className="h-4 w-4 text-brand-600" />
                      <span>Why CogniLearn AI Recommended This:</span>
                    </div>
                    <p className="text-xs text-brand-800/90 leading-relaxed font-normal">
                      {rec.aiReasoning}
                    </p>
                    <div className="pt-2 flex flex-wrap items-center gap-4 text-[11px] font-semibold text-brand-700">
                      <span>🎯 Target Gap: <strong className="text-slate-800">{rec.targetSkillGap}</strong></span>
                      <span>📈 Potential: <strong className="text-emerald-700">{rec.impactPotential}</strong></span>
                    </div>
                  </div>
                </div>

                {/* Right Action Side: Image & Buttons */}
                <div className="w-full lg:w-72 shrink-0 flex flex-col justify-between gap-4">
                  <div className="relative h-36 w-full overflow-hidden rounded-2xl bg-slate-100">
                    <img
                      src={rec.thumbnail}
                      alt={rec.title}
                      className="h-full w-full object-cover group-hover:scale-105 transition-transform duration-300"
                    />
                    <div className="absolute inset-0 bg-gradient-to-t from-black/60 to-transparent" />
                    <span className="absolute bottom-2.5 left-3 text-xs font-bold text-white">
                      Level: {rec.difficulty}
                    </span>
                  </div>

                  <div className="space-y-2">
                    <button
                      onClick={() => {
                        setCurrentPage('quiz');
                        addToast('Opening Adaptive Drill', `Loaded interactive remediation for: ${rec.targetSkillGap}`, 'success');
                      }}
                      className="flex w-full items-center justify-center gap-2 rounded-xl bg-brand-600 py-2.5 text-xs font-bold text-white hover:bg-brand-700 shadow-md shadow-brand-500/20 transition-all"
                    >
                      <span>Start Learning Now</span>
                      <ArrowRight className="h-3.5 w-3.5" />
                    </button>

                    <button
                      onClick={() => handleAddToPlan(rec)}
                      disabled={isAdded}
                      className={`flex w-full items-center justify-center gap-1.5 rounded-xl border py-2.5 text-xs font-bold transition-all ${
                        isAdded
                          ? 'border-emerald-200 bg-emerald-50 text-emerald-700 cursor-default'
                          : 'border-slate-200 bg-white text-slate-700 hover:bg-slate-50'
                      }`}
                    >
                      {isAdded ? (
                        <>
                          <CheckCircle2 className="h-3.5 w-3.5 text-emerald-600" />
                          <span>Added to Study Plan</span>
                        </>
                      ) : (
                        <>
                          <PlusCircle className="h-3.5 w-3.5 text-slate-500" />
                          <span>Add to Study Planner</span>
                        </>
                      )}
                    </button>
                  </div>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
